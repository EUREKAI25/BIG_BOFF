# ── Private helpers ───────────────────────────────────────────────────────────

def _issuer_repr(issuer: Optional[DocumentIssuer], brand_name: str) -> str:
    if issuer is None:
        return f'{{"name": "{brand_name}"}}'
    data = issuer.model_dump(exclude_none=True)
    import json
    return json.dumps(data, ensure_ascii=False)


def _bank_repr(bank: Optional[BankDetails]) -> str:
    if bank is None:
        return "None"
    data = bank.model_dump(exclude_none=True)
    import json
    return f"BankDetails(**{json.dumps(data, ensure_ascii=False)})"
